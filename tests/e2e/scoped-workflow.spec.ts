import { test,expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { icaPreset } from '../../src/lib/projects/ica-preset'
const origin='http://127.0.0.1:3201'
test('owner runs one step, switches to chain, and regenerates one post without replacing other approved content',async({page,request})=>{
 const result=await request.post('/api/projects',{headers:{origin},data:{name:'Phạm vi chạy UI',brief:{...icaPreset,contact:'0986000000'},requestId:randomUUID()}})
 const {project}=await result.json()
 const read=async()=>(await (await request.get('/api/projects/'+project.id)).json()).project
 await page.addInitScript(id=>localStorage.setItem('mission-control.active-project.v1',id),project.id)
 await page.goto('/#he-thong-1')
 const controls=page.getByTestId('run-scope')
 await controls.getByRole('radio',{name:'Một bước',exact:true}).check()
 await controls.getByRole('button',{name:'Chạy bước đã chọn',exact:true}).click()
 await page.getByRole('button',{name:'Duyệt 1 và dừng',exact:true}).click()
 await expect.poll(async()=> (await read()).status).toBe('paused')
 expect((await read()).jobs).toHaveLength(1)
 await controls.getByLabel('Bước muốn chạy').selectOption('2')
 await controls.getByRole('button',{name:'Chạy bước đã chọn',exact:true}).click()
 await expect.poll(async()=> (await read()).jobs.length).toBe(2)
 await expect.poll(async()=> (await read()).status).toBe('paused')
 let saved=await read()
 expect(saved.jobs).toHaveLength(2);expect(saved.artifacts.filter((a:any)=>a.systemId===3)).toHaveLength(0)
 await controls.getByRole('radio',{name:'Cả chuỗi',exact:true}).check()
 await controls.getByRole('button',{name:'Chuyển sang chạy cả chuỗi',exact:true}).click()
 await page.getByRole('button',{name:'Duyệt 2 và tiếp tục',exact:true}).click()
 await expect(page.getByRole('status').filter({hasText:'Đã hoàn tất 5 hệ thống'})).toBeVisible()
 const before=await read(),old=before.artifacts.find((a:any)=>a.key==='post:Facebook'&&a.status==='approved')
 await page.getByRole('navigation',{name:'Hệ thống'}).getByRole('button',{name:'Chuyển đổi',exact:true}).click()
 const card=page.locator('summary').filter({hasText:/^Bài đăng Facebook /}).locator('..')
 await card.locator(':scope > summary').click()
 await card.getByRole('button',{name:'Tạo lại riêng',exact:true}).click()
 await expect(card).toContainText('Xong mục này sẽ dừng')
 await card.getByRole('button',{name:'Xác nhận tạo lại',exact:true}).click()
 await expect(page.getByRole('button',{name:'Duyệt 2 và dừng',exact:true})).toBeVisible()
 saved=await read()
 const current=saved.artifacts.filter((a:any)=>a.status!=='stale')
 const newer=current.find((a:any)=>a.key==='post:Facebook')
 expect(newer.id).not.toBe(old.id);expect(newer.version).toBe(old.version+1)
 for(const a of before.artifacts.filter((a:any)=>a.status==='approved'&&a.systemId<=3&&a.id!==old.id))expect(current.find((b:any)=>b.id===a.id)).toEqual(a)
 expect(saved.jobs.at(-1).outputKeys).toEqual(['post:Facebook'])
 await card.locator(':scope > summary').click()
 await card.getByText('Xem lịch sử phiên bản',{exact:true}).click()
 await expect(card).toContainText('đã thay thế / lỗi thời')
 await page.getByRole('button',{name:'Duyệt 2 và dừng',exact:true}).click()
 await expect.poll(async()=> (await read()).status).toBe('paused')
 expect((await read()).jobs).toHaveLength(6)
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await controls.screenshot({path:'.local/e2e-results/priority2-scope-mobile.png'})
})
