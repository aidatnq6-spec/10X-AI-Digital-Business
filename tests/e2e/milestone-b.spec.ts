test('worker advances a saved project without any project browser page being open',async({request})=>{
 const created=await request.post('/api/projects',{headers:{origin},data:{name:'Không mở tab',brief:icaPreset,requestId:randomUUID()}})
 expect(created.status()).toBe(201)
 const {project}=await created.json()
 const start=await request.post(`/api/projects/${project.id}/commands`,{headers:{origin},data:{type:'start',requestId:randomUUID()}})
 expect(start.status()).toBe(200)
 await expect.poll(async()=>{const result=await request.get(`/api/projects/${project.id}`);return (await result.json()).project.status},{timeout:10000}).toBe('waiting_approval')
 const result=await (await request.get(`/api/projects/${project.id}`)).json()
 expect(result.project.workflow.gate).toBe(1)
})
test('concurrent revisions leave the unsaved editor accessible and prevent switching projects',async({page,request})=>{
 await request.post('/api/projects',{headers:{origin},data:{name:'Dự án đối chiếu khác',brief:icaPreset,requestId:randomUUID()}})
 const created=await request.post('/api/projects',{headers:{origin},data:{name:'Kiểm tra bản sửa',brief:icaPreset,requestId:randomUUID()}})
 const {project}=await created.json()
 await request.post(`/api/projects/${project.id}/commands`,{headers:{origin},data:{type:'start',requestId:randomUUID()}})
 await expect.poll(async()=>((await (await request.get(`/api/projects/${project.id}`)).json()).project.status),{timeout:10000}).toBe('waiting_approval')
 await page.addInitScript(id=>localStorage.setItem('mission-control.active-project.v1',id),project.id)
 await page.goto('/#he-thong-1')
 const artifact=(await (await request.get(`/api/projects/${project.id}`)).json()).project.artifacts.find((a:{status:string})=>a.status!=='stale')
 const card=page.locator('details').filter({has:page.locator('summary').filter({hasText:'Định vị và bộ chào bán'})}).first()
 if(await card.getAttribute('open')===null) await card.locator(':scope > summary').click()
 await card.getByRole('button',{name:'Sửa nội dung',exact:true}).click()
 const draft=artifact.content+'\nBản đang nhập chưa lưu của tôi.'
 await page.getByLabel('Sửa nội dung',{exact:true}).fill(draft)
 await expect(page.getByLabel('Chọn đề bài đã lưu')).toBeDisabled()
 await request.post(`/api/projects/${project.id}/commands`,{headers:{origin},data:{type:'reviseArtifact',artifactId:artifact.id,content:artifact.content+'\nBản đã sửa ở cửa sổ khác.',requestId:randomUUID()}})
 await page.getByRole('button',{name:'Kiểm tra đồng bộ',exact:true}).click()
 await expect(page.getByText('Phiên bản gốc đã thay đổi.',{exact:false})).toBeVisible()
 await expect(page.getByLabel('Sửa nội dung',{exact:true})).toHaveValue(draft)
 await page.getByRole('button',{name:'Dùng bản sửa của tôi trên phiên bản mới'}).click()
 await page.getByRole('button',{name:'Lưu phiên bản nội dung'}).click()
 await expect(page.getByLabel('Chọn đề bài đã lưu')).toBeEnabled()
 const latest=(await (await request.get(`/api/projects/${project.id}`)).json()).project
 expect(latest.artifacts.some((a:{status:string;content:string})=>a.status!=='stale'&&a.content===draft)).toBe(true)
})
